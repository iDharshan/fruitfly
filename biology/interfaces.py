    arena_height: float = 1000.0

    # Motor & Kinematics
    v_cruise: float = 120.0           # Baseline cruising speed px/s
    v_min: float = 30.0
    v_max: float = 180.0
    omega_max: float = 4.5            # Max angular velocity rad/s
    omega_bias_max: float = 2.5       # Learned steering bias authority
    z_max: float = 50.0               # Max flight altitude
    z_cruise: float = 30.0            # Default cruising altitude
    z_contact: float = 2.0            # Threshold below which brush contacts canvas
    pen_flow_rate: float = 0.15       # Pigment deposition speed per sec at P=1
    pigment_capacity: float = 1.0     # Max pigment volume in brush reservoir
