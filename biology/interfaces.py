    tau_pfl3: float = 0.025
    k_div: float = 0.012
    substeps_per_frame: int = 8
    w_ee: float = 2.4
    w_ep: float = 1.8
    w_pe_ratio: float = 2.09
    sigma_ee: float = 0.60
    shift_angle: float = np.pi / 4.0
    noise_sigma: float = 0.01
    k_turn_drive: float = 2.5
    k_pfl3_drive: float = 2.8

    # Sensory Olfaction
    sigma_odor: float = 120.0         # Spatial plume radius
    beta_odor: float = 3.0            # AL tanh gain
    n_odor_channels: int = 4          # R, G, B, Y

    # Sensory Vision
