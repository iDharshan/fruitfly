"""
Biological interfaces and immutable data contracts for Fruitfly V2.
Guarantees clean boundary between frozen biological systems, sensory transducers, and learned RL policy.
"""

from dataclasses import dataclass, field
import numpy as np


@dataclass(frozen=True)
class CompassState:
    """
    Immutable state snapshot emitted by the Frozen CANN Central Complex compass.
    Cannot be modified by external policies.
    """
    heading: float            # Decoded azimuth theta in [-pi, pi)
    sin_heading: float        # sin(theta) (smooth cyclic representation)
    cos_heading: float        # cos(theta)
    coherence: float          # Bump quality in [0, 1]
    amplitude: float          # Vector sum amplitude
    torque: float             # Differential P-EN activation (Right - Left)
    epg_activity: np.ndarray  # Shape (48,), normalized [0, 1], read-only
    pen_left_mean: float      # Left shifter activity
    pen_right_mean: float     # Right shifter activity
    pfl3_bias: float          # Biological steering bias from PFL3 in [-1, 1]

    def to_observation_vector(self) -> np.ndarray:
        """Compact 5D vector matching rl.observation_space['compass']."""
        return np.array(
            [self.sin_heading, self.cos_heading, self.coherence, self.torque, self.pfl3_bias],
            dtype=np.float32,
        )


@dataclass(frozen=True)
class SensoryState:
    """
    Immutable snapshot of biological sensory perception (chemical and visual).
    """
    odor_concentrations: np.ndarray   # Raw concentrations at antennae, shape (4,)
    al_glomeruli: np.ndarray          # Antennal Lobe rate-coded outputs, shape (4,) in [0, 1]
    canvas_bearing: float             # Egocentric bearing to canvas center in [-pi, pi)
    canvas_dist_norm: float           # Normalized distance to canvas [0, 1]
    pot_bearings: np.ndarray          # Egocentric bearings to pots R, G, B, Y in [-pi, pi), shape (4,)
    pot_distances_norm: np.ndarray    # Normalized distances to pots R, G, B, Y in [0, 1], shape (4,)
    min_pot_dist: float               # Normalized distance to closest pot in [0, 1]
    altitude_norm: float              # Normalized altitude z / z_max in [0, 1]

    def to_sensory_vector(self) -> np.ndarray:
        """Compact 8D vector matching rl.observation_space['sensory']."""
        return np.array(
            [
                self.canvas_bearing / np.pi,  # Normalized [-1, 1]
                self.canvas_dist_norm * 2.0 - 1.0,  # [-1, 1]
                self.pot_bearings[0] / np.pi,
                self.pot_bearings[1] / np.pi,
                self.pot_bearings[2] / np.pi,
                self.pot_bearings[3] / np.pi,
                self.min_pot_dist * 2.0 - 1.0,
                self.altitude_norm * 2.0 - 1.0,
            ],
            dtype=np.float32,
        )

    def to_odor_vector(self) -> np.ndarray:
        """Compact 4D vector matching rl.observation_space['odor']."""
        return np.clip(self.al_glomeruli, 0.0, 1.0).astype(np.float32)


@dataclass(frozen=True)
class BrainOutput:
    """
    Output generated by the descending biological premotor bridge.
    Controls physical kinematics of the fly body and brush actuator.
    """
    steering_omega: float             # Net angular steering velocity in rad/s
    forward_velocity: float           # Forward speed in px/s
    altitude_command: float           # Target altitude or climb rate
    pen_pressure: float               # Brush pressure in [0, 1]
    pen_down: bool                    # Physical brush contact intent


